biobert_model = AutoModel.from_pretrained("dmis-lab/biobert-base-cased-v1.1").to(DEVICE)
biobert_model.eval()

def encode_text_batch(texts):
    embeddings = []
    for i in range(0, len(texts), BATCH_SIZE):
        batch = texts[i:i+BATCH_SIZE]
        tokens = biobert_tokenizer(batch, return_tensors="pt", truncation=True,
                                   padding=True, max_length=512).to(DEVICE)
        with torch.no_grad():
            outputs = biobert_model(**tokens)
            batch_emb = outputs.last_hidden_state.mean(dim=1)
            embeddings.append(batch_emb.cpu().numpy().astype("float32"))
        del tokens, outputs, batch_emb
        torch.cuda.empty_cache()
    return np.vstack(embeddings)

# 6️⃣ Text preprocessing
ABBREVIATIONS = {"mi":"myocardial infarction","bp":"blood pressure","dm":"diabetes mellitus",
                 "copd":"chronic obstructive pulmonary disease","cvd":"cardiovascular disease","htn":"hypertension"}

def clean_text(text:str):
    text = re.sub(r"\[[0-9]+\]", " ", text)
    text = re.sub(r"\([0-9]{4}\)", " ", text)
    text = re.sub(r"[^a-zA-Z0-9.,;:%()\- ]", " ", text)
    return re.sub(r"\s+"," ", text).strip()

def expand_abbreviations(text:str):
    return " ".join(ABBREVIATIONS.get(w.lower(), w) for w in text.split())

def sentence_split(text:str): return re.split(r'(?<=[.!?])\s+', text)

def chunk_sentences(text:str, max_words=180):
    sentences = sentence_split(text)
    chunks, sentence_map, current, count = [], [], [], 0
    for sent in sentences:
        words = sent.split()
        if count + len(words) > max_words and current:
            chunks.append(" ".join(current))
            sentence_map.append(current)
            current, count = [], 0
        current.append(sent)
        count += len(words)
    if current:
        chunks.append(" ".join(current))
        sentence_map.append(current)
    return chunks, sentence_map

def preprocess_document(text:str):
    return chunk_sentences(expand_abbreviations(clean_text(text)))

def preprocess_query(text:str):
    return expand_abbreviations(clean_text(text))

def is_valid_chunk(text:str, min_words=25):
    return len(text.split())>=min_words

