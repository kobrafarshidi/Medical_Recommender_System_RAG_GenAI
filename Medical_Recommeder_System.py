user_profile = {"user_id":"user_001", "specialty":None, "intent_bias":{"treatment":1.2,"review":1.0,"diagnosis":1.1}, "clicked_pmids":[]}

def set_user_profile(user_id, specialty):
    user_profile["user_id"] = user_id
    user_profile["specialty"] = specialty

def log_interaction(user, pmid):
    user["clicked_pmids"].append(pmid)

def build_user_embedding(user):
    if not user["clicked_pmids"]: return None
    embs = []
    for pmid, _, text in metadata:
        if pmid in user["clicked_pmids"]:
            embs.append(encode_text_batch([text])[0])
    if embs:
        return np.mean(embs, axis=0)
    return None

# 9️⃣ Intent Classification
INTENT_KEYWORDS = {"treatment":["treat","therapy","drug","headache","pain"],
                   "diagnosis":["diagnosis","symptom","test"],
                   "review":["review","survey"],
                   "education":["guide","tutorial"]}

def classify_intent(query:str):
    q = query.lower()
    for intent,kws in INTENT_KEYWORDS.items():
        if any(k in q for k in kws): return intent
    return "education"

# 🔹 Entity Extraction + Graph
def extract_entities(text):
    doc = nlp(text)
    entities = [(ent.text, ent.label_) for ent in doc.ents]
    # Build simple co-occurrence graph
    G = nx.Graph()
    for e,_ in entities: G.add_node(e)
    for i in range(len(entities)):
        for j in range(i+1,len(entities)):
            G.add_edge(entities[i][0], entities[j][0])
    return entities, G

# 1️⃣0️⃣ Retrieval + Recommender scoring
def retrieve(query_emb,k=10):
    _, idxs = index.search(query_emb,k)
    return idxs[0]

def recommender_score(query, idx, intent, user_emb=None):
    rel_score = 1.0
    intent_weight = user_profile["intent_bias"].get(intent,1.0)
    pers_score = 1.0
    if user_emb is not None:
        item_emb = encode_text_batch([metadata[idx][2]])[0]
        pers_score += float(np.dot(user_emb, item_emb.T))
    query_entities,_ = extract_entities(query)
    doc_entities,_ = extract_entities(metadata[idx][2])
    kb_score = len(set([e[0] for e in doc_entities]) & set([e[0] for e in query_entities])) + 1
    return rel_score * intent_weight * pers_score * kb_score

def recommender_rerank(query, candidate_indices, user):
    intent = classify_intent(query)
    user_emb = build_user_embedding(user)
    scores = [recommender_score(query, idx, intent, user_emb) for idx in candidate_indices]
    ranked = np.argsort(scores)[::-1]
    return [candidate_indices[i] for i in ranked]

# 1️⃣1️⃣ Load Flan-T5-base
llm_tokenizer = AutoTokenizer.from_pretrained("google/flan-t5-base")
llm_model = AutoModelForSeq2SeqLM.from_pretrained("google/flan-t5-base").to(DEVICE)

def call_llm(prompt):
    inputs = llm_tokenizer(prompt, return_tensors="pt", truncation=True, max_length=MAX_LLM_INPUT_TOKENS).to(DEVICE)
    with torch.no_grad():
        output = llm_model.generate(**inputs, max_new_tokens=MAX_LLM_OUTPUT_TOKENS)
    return llm_tokenizer.decode(output[0], skip_special_tokens=True)

# 1️⃣2️⃣ RAG + Explainability + PMIDs + Sentence-level
def search_and_explain(query, top_k_chunks=5):
    emb = encode_text_batch([preprocess_query(query)])[0:1]
    idxs = retrieve(emb, k=top_k_chunks*5)
    candidate_pmids = [metadata[i][0] for i in idxs]
    idxs_rerank = recommender_rerank(query, idxs, user_profile)[:top_k_chunks]
    topk_pmids = [metadata[i][0] for i in idxs_rerank]

    contexts, citations = [], []
    for i in idxs_rerank:
        log_interaction(user_profile, metadata[i][0])
        sentences = sentence_maps[i]
        for s in sentences:
            if any(w.lower() in s.lower() for w in query.lower().split()):
                contexts.append(s)
                citations.append(metadata[i][0])
                break

    context_text = ' '.join(contexts)[:MAX_LLM_INPUT_TOKENS]
    intent = classify_intent(query)
    prompt = f"""
You are explaining WHY the following articles were recommended
for a {intent} task. Use only the context below and provide citations.

Context:
{context_text}

Citations (PMID):
{', '.join(map(str,citations))}

Explain the recommendation.
"""
    explanation = call_llm(prompt)
    return explanation, candidate_pmids, topk_pmids

